import type { Article, ArticleStatus, Edition, SiteSettings } from '../types.ts'

const DEMO_NOTE =
  '<blockquote><p>هذا النص محتوى تجريبي أُعد لعرض هيئة الجريدة، وهو ليس تغطية لحدث واقعي.</p></blockquote>'

function blocks(parts: string[]): string {
  return `${parts.map((part) => (part.startsWith('<') ? part : `<p>${part}</p>`)).join('')}${DEMO_NOTE}`
}

function makeArticle(input: {
  id: string
  title: string
  slug: string
  summary: string
  content: string
  categoryId: string
  author: string
  publishedAt: string | null
  status?: ArticleStatus
  featured?: boolean
  breaking?: boolean
  hours?: number
  minutes?: number
}): Article {
  const category = DEFAULT_CATEGORIES.find((item) => item.id === input.categoryId)
  const publishedAt = input.publishedAt
    ? atLocalDate(input.publishedAt, input.hours ?? 9, input.minutes ?? 0)
    : null
  const stamp = publishedAt ?? atLocalDate('2026-10-25', 8, 0)
  return {
    id: input.id,
    title: input.title,
    slug: input.slug,
    summary: input.summary,
    content: input.content,
    categoryId: input.categoryId,
    categorySlug: category?.slug ?? input.categoryId,
    categoryName: category?.name ?? input.categoryId,
    author: input.author,
    imageUrl: `/demo/images/${input.categoryId}.svg`,
    seoTitle: '',
    seoDescription: '',
    status: input.status ?? 'published',
    featured: input.featured ?? false,
    breaking: input.breaking ?? false,
    isDemo: true,
    keywords: buildKeywords(input.title, input.summary, category?.name ?? '', input.author),
    publishedAt,
    createdAt: stamp,
    updatedAt: stamp,
    createdBy: 'demo',
  }
}

