function demoEdition(input: {
  issueNumber: number
  title: string
  description: string
  publishedAt: string | null
  status?: 'draft' | 'published'
}): Edition {
  const stamp = input.publishedAt ? atLocalDate(input.publishedAt, 6, 0) : atLocalDate('2026-10-25', 7, 0)
  return {
    id: `demo-${input.issueNumber}`,
    issueNumber: input.issueNumber,
    title: input.title,
    description: input.description,
    coverImageUrl: `/demo/covers/${input.issueNumber}.svg`,
    pdfUrl: input.status === 'draft' ? '' : '/demo/issue-sample.pdf',
    status: input.status ?? 'published',
    isDemo: true,
    publishedAt: input.publishedAt ? stamp : null,
    createdAt: stamp,
    updatedAt: stamp,
  }
}

